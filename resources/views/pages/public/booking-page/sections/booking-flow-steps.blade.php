<ol class="booking-flow-steps">
  <li class="booking-flow-step">
    <span class="booking-flow-step-number">01</span>
    <div class="booking-flow-step-body">
      <h3 class="booking-flow-title">Kirim request booking</h3>
      <p class="booking-flow-text">Isi tanggal, lokasi, paket, dan detail acara. Data Anda akan masuk ke antrean review admin. Anda akan menerima bukti pengajuan (PDF) dan Case ID untuk pelacakan status.</p>
    </div>
  </li>
  <li class="booking-flow-step">
    <span class="booking-flow-step-number">02</span>
    <div class="booking-flow-step-body">
      <h3 class="booking-flow-title">Review dan approval</h3>
      <p class="booking-flow-text">Admin mengecek ketersediaan tim dan kecocokan paket. Jika disetujui, billing diinisialisasi dan admin menyiapkan tagihan DP Anda.</p>
    </div>
  </li>
  <li class="booking-flow-step">
    <span class="booking-flow-step-number">03</span>
    <div class="booking-flow-step-body">
      <h3 class="booking-flow-title">Pembayaran DP</h3>
      <p class="booking-flow-text">Tagihan DP dibuat oleh admin. DP dibayar sesuai jenis acara (Wedding 15%, Non-wedding 10%). Batas waktu pembayaran maksimal 3 hari setelah approval. Slot hanya terkunci setelah DP diverifikasi.</p>
    </div>
  </li>
  <li class="booking-flow-step">
    <span class="booking-flow-step-number">04</span>
    <div class="booking-flow-step-body">
      <h3 class="booking-flow-title">Pembayaran pelunasan</h3>
      <p class="booking-flow-text">Setelah DP diverifikasi, tagihan pelunasan dibuat. Pelunasan dilakukan maksimal H-1 acara dan diverifikasi manual oleh admin. Booking resmi dikunci (Confirmed) setelah pelunasan terverifikasi.</p>
    </div>
  </li>
  <li class="booking-flow-step">
    <span class="booking-flow-step-number">05</span>
    <div class="booking-flow-step-body">
      <h3 class="booking-flow-title">Eksekusi acara</h3>
      <p class="booking-flow-text">Tim Etherno hadir di lokasi sesuai jadwal untuk dokumentasi acara Anda. Setelah acara selesai, booking ditandai sebagai Complete.</p>
    </div>
  </li>
  <li class="booking-flow-step">
    <span class="booking-flow-step-number">06</span>
    <div class="booking-flow-step-body">
      <h3 class="booking-flow-title">Reschedule & force majeure</h3>
      <p class="booking-flow-text">Jika butuh perubahan jadwal, Anda dapat mengajukan reschedule minimal 14 hari sebelum acara via halaman cek status booking. Untuk kondisi force majeure, tim Etherno akan mengajukan opsi reschedule atau refund yang perlu disetujui Anda.</p>
    </div>
  </li>
</ol>
